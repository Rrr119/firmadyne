#!/usr/bin/env python3
"""Health check for an emulated FIRMADYNE firmware image.

Answers two questions that the original workflow leaves open:

1. Did the guest actually boot, or did it get stuck in an early boot stage?
2. Are the expected network services reachable on the emulated host?

The check combines evidence from the QEMU serial log (boot stage / failure
signature detection) with live network probes (ICMP + TCP connect).  It emits
a machine-readable JSON report and returns a non-zero exit status on failure,
so it can be used both interactively and from automated pipelines.
"""

import argparse
import json
import os
import re
import shutil
import socket
import subprocess
import sys
import time


# Ordered boot milestones.  Each stage maps a serial-log marker to a
# human-readable description of where emulation has progressed to.
BOOT_STAGES = [
    ("kernel_start", re.compile(r"Linux version|Booting Linux"),
     "kernel started"),
    ("rootfs_mount", re.compile(r"VFS: Mounted root|Mounted root filesystem|mounted filesystem"),
     "root filesystem mounted"),
    ("userspace_init", re.compile(r"firmadyne: .*execve|init started|BusyBox"),
     "userspace init started"),
    ("network_up", re.compile(r"__inet_insert_ifa|link becomes ready|eth[0-9].*UP|br[0-9].*UP"),
     "guest network interface configured"),
    ("login_ready", re.compile(r"login:|Welcome to|Press Enter|starting PID|init process"),
     "login/services startup reached"),
]

# Fatal signatures, ordered from earliest (lowest level) to latest boot
# stage.  The first match wins and determines the reported stuck point.
FAILURE_SIGNATURES = [
    ("qemu_missing", re.compile(r"qemu-system-[a-z]+: command not found", re.IGNORECASE),
     "qemu_startup",
     "QEMU binary could not be started (check qemu-system-* installation)"),
    ("kernel_panic", re.compile(r"Kernel panic - not syncing", re.IGNORECASE),
     "kernel",
     "kernel panic before userspace came up"),
    ("rootfs_fail", re.compile(r"Unable to mount root fs|VFS: Cannot open root device|unknown-block"),
     "rootfs_mount",
     "root filesystem could not be mounted (regenerate the image with makeImage.sh)"),
    ("no_init", re.compile(r"No working init found|Failed to execute /firmadyne/preInit"),
     "userspace_init",
     "init process could not be executed (check init= kernel parameter)"),
    ("oops", re.compile(r"Kernel Oops|do_page_fault.*SIG(KILL|SEGV)", re.IGNORECASE),
     "userspace_init",
     "kernel oops / fatal userspace fault during service startup"),
    ("segfault", re.compile(r"Segmentation fault|SIGSEGV", re.IGNORECASE),
     "service_start",
     "a userspace service crashed with SIGSEGV (often an unhandled NVRAM key)"),
]


def read_text(path):
    try:
        with open(path, "rb") as handle:
            return handle.read().decode("utf-8", "replace")
    except OSError:
        return ""


def detect_guest_ip(run_script):
    """Extract the guest IP from the network script generated by makeNetwork.py.

    The generated script contains lines of the form:
    sudo ip route add 192.168.0.100 via 192.168.0.100 dev ...
    """
    if not run_script or not os.path.exists(run_script):
        return None
    text = read_text(run_script)
    match = re.search(r"ip route add\s+(\d+\.\d+\.\d+\.\d+)\s+via", text)
    return match.group(1) if match else None


def analyze_serial(log_text):
    """Walk the serial log and return reached stages and any fatal signature."""
    reached = []
    for stage_id, pattern, description in BOOT_STAGES:
        if pattern.search(log_text):
            reached.append({"stage": stage_id, "description": description})

    failure = None
    for failure_id, pattern, stage, explanation in FAILURE_SIGNATURES:
        match = pattern.search(log_text)
        if match:
            line = next((ln.strip() for ln in log_text.splitlines()
                         if pattern.search(ln)), match.group(0))
            failure = {
                "id": failure_id,
                "stage": stage,
                "explanation": explanation,
                "evidence": line[:300],
            }
            break
    return reached, failure


def ping_alive(host, timeout):
    if not shutil.which("ping"):
        return None
    try:
        result = subprocess.run(
            ["ping", "-c", "1", "-W", str(max(1, int(timeout))), host],
            stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        return result.returncode == 0
    except OSError:
        return None


def tcp_open(host, port, timeout):
    try:
        with socket.create_connection((host, port), timeout=timeout):
            return True
    except OSError:
        return False


def wait_for_ports(host, ports, per_try_timeout, deadline):
    """Poll every requested port until all are open or the deadline passes."""
    results = {str(port): {"open": False, "attempts": 0} for port in ports}
    while ports and time.time() < deadline:
        still_closed = []
        for port in ports:
            entry = results[str(port)]
            entry["attempts"] += 1
            if tcp_open(host, port, per_try_timeout):
                entry["open"] = True
            else:
                still_closed.append(port)
        ports = still_closed
        if ports:
            time.sleep(min(1.0, max(0.0, deadline - time.time())))
    return results


def parse_ports(spec):
    ports = []
    for item in spec.split(","):
        item = item.strip()
        if not item:
            continue
        value = int(item)
        if not 1 <= value <= 65535:
            raise ValueError("port out of range: %d" % value)
        ports.append(value)
    return ports


def build_report(iid, args, log_path, run_script):
    log_text = read_text(log_path)
    log_seen = os.path.exists(log_path)
    stages, serial_failure = analyze_serial(log_text)

    host = args.host or detect_guest_ip(run_script)
    ports = parse_ports(args.ports) if args.ports else []

    report = {
        "image_id": iid,
        "timestamp": time.strftime("%Y-%m-%dT%H:%M:%S%z"),
        "guest_ip": host,
        "serial_log": log_path,
        "serial_log_seen": log_seen,
        "boot_stages": stages,
        "last_boot_stage": stages[-1]["stage"] if stages else None,
        "serial_failure": serial_failure,
        "network": {"icmp": None, "ports": {}},
        "success": False,
        "failure_stage": None,
        "reason": None,
    }

    if not log_seen:
        report["failure_stage"] = "qemu_startup"
        report["reason"] = "no serial log produced; QEMU never started or exited immediately"
        return report

    if serial_failure:
        report["failure_stage"] = serial_failure["stage"]
        report["reason"] = serial_failure["explanation"]
        return report

    if not host:
        report["failure_stage"] = "network_inference"
        report["reason"] = "could not determine guest IP (pass --host or rerun inferNetwork.sh)"
        return report

    report["network"]["icmp"] = ping_alive(host, args.timeout)

    if ports:
        deadline = time.time() + args.timeout
        report["network"]["ports"] = wait_for_ports(
            host, ports, min(2.0, args.timeout), deadline)
        closed = [port for port, entry in report["network"]["ports"].items()
                  if not entry["open"]]
        if closed:
            report["failure_stage"] = "service_start"
            report["reason"] = "guest booted but service port(s) not listening: %s" % ", ".join(closed)
            return report

    # No explicit ports: fall back to ICMP as the liveness signal.
    if not ports and report["network"]["icmp"] is False:
        report["failure_stage"] = "network_up"
        report["reason"] = "guest never became reachable over the network (no ICMP reply)"
        return report

    if not stages:
        report["failure_stage"] = "kernel_start"
        report["reason"] = "serial log contains no recognizable kernel boot messages"
        return report

    report["success"] = True
    report["reason"] = "emulation healthy: boot milestones reached and probes passed"
    return report


def main():
    parser = argparse.ArgumentParser(
        description="Health check for an emulated FIRMADYNE firmware image.")
    parser.add_argument("iid", type=int, help="firmware image ID")
    parser.add_argument("-S", "--scratch", default=os.environ.get("SCRATCH_DIR", "scratch"),
                        help="scratch directory (default: ./scratch or $SCRATCH_DIR)")
    parser.add_argument("-H", "--host", help="guest IP address (auto-detected from run.sh if omitted)")
    parser.add_argument("-p", "--ports", default="80,443",
                        help="comma-separated TCP ports that must be listening; '' disables TCP checks")
    parser.add_argument("-t", "--timeout", type=float, default=60.0,
                        help="seconds to keep probing for services (default: 60)")
    parser.add_argument("-j", "--json", action="store_true",
                        help="print only the JSON report (default: human summary + JSON)")
    parser.add_argument("-o", "--report", help="also write the JSON report to this file")
    args = parser.parse_args()

    work_dir = os.path.join(args.scratch, str(args.iid))
    # Prefer the final (post network-inference) log, then the initial one.
    log_path = os.path.join(work_dir, "qemu.final.serial.log")
    if not os.path.exists(log_path):
        log_path = os.path.join(work_dir, "qemu.initial.serial.log")
    run_script = os.path.join(work_dir, "run.sh")

    # In foreground mode QEMU's output flows through `tee`, which creates the
    # log lazily; give it a moment instead of declaring "no serial log" at once.
    if not os.path.exists(log_path):
        deadline = time.time() + min(10.0, args.timeout)
        while time.time() < deadline and not os.path.exists(log_path):
            time.sleep(0.5)

    report = build_report(args.iid, args, log_path, run_script)

    payload = json.dumps(report, indent=2, sort_keys=True)
    if args.report:
        with open(args.report, "w") as handle:
            handle.write(payload + "\n")

    if args.json:
        print(payload)
    else:
        status = "SUCCESS" if report["success"] else "FAILURE"
        print("[healthcheck] image %s: %s" % (args.iid, status))
        for stage in report["boot_stages"]:
            print("  [ok] stage %-15s %s" % (stage["stage"], stage["description"]))
        if report["guest_ip"]:
            print("  guest ip: %s  icmp: %s" %
                  (report["guest_ip"], report["network"]["icmp"]))
            for port, entry in sorted(report["network"]["ports"].items(),
                                      key=lambda item: int(item[0])):
                mark = "open" if entry["open"] else "closed"
                print("  tcp/%s: %s (%d attempt(s))" % (port, mark, entry["attempts"]))
        if report["success"]:
            print("  reason: %s" % report["reason"])
        else:
            print("  [FAIL] stuck at stage: %s" % report["failure_stage"])
            print("         reason: %s" % report["reason"])
            if report["serial_failure"]:
                print("         evidence: %s" % report["serial_failure"]["evidence"])
        print("  report: %s" % (args.report or "(use -o to save)"))

    sys.exit(0 if report["success"] else 1)


if __name__ == "__main__":
    main()
